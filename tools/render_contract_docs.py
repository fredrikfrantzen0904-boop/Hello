"""Render ``specifications/contracts/FIELDS.md`` from the contract declarations.

The field tables are generated, never edited by hand, so the documentation
cannot drift from the code.  ``--check`` fails when the committed file is stale.
"""

from __future__ import annotations

import argparse
import sys
from enum import Enum
from pathlib import Path

import gie.contracts
from gie.contracts._spec import EnumOf, FieldType, ListOf, Obj, Opt, Record
from gie.contracts.model_version import MODEL_STATUS_TRANSITIONS
from gie.contracts.order_event import ORDER_TRANSITIONS
from gie.contracts.registry import all_contracts
from gie.core.errors import ALL_ERROR_TYPES
from gie.core.ids import ID_PREFIXES
from gie.core.ordering import StreamRank

OUTPUT = Path(__file__).resolve().parents[1] / "specifications" / "contracts" / "FIELDS.md"


def _walk(ftype: FieldType, records: dict[str, type[Record]], enums: dict[str, type[Enum]]) -> None:
    if isinstance(ftype, (Opt, ListOf)):
        _walk(ftype.inner, records, enums)
    elif isinstance(ftype, EnumOf):
        enums.setdefault(ftype.enum_type.__name__, ftype.enum_type)
    elif isinstance(ftype, Obj) and ftype.record_type.__name__ not in records:
        records[ftype.record_type.__name__] = ftype.record_type
        for spec in ftype.record_type.FIELD_SPECS:
            _walk(spec.ftype, records, enums)


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(record_type: type[Record]) -> list[str]:
    lines = ["| field | type | required | unit | meaning |", "|---|---|---|---|---|"]
    for spec in record_type.FIELD_SPECS:
        lines.append(
            f"| `{spec.name}` | {_esc(spec.ftype.describe())} | {'yes' if spec.required else 'no'} "
            f"| {_esc(spec.unit or '')} | {_esc(spec.doc)} |"
        )
    if record_type.ALL_INVARIANTS:
        lines += ["", "Invariants (checked whenever a record is constructed or decoded):", ""]
        lines += [f"- **{rule.id}** - {rule.text}" for rule in record_type.ALL_INVARIANTS]
    return lines


def _doc(obj: object) -> str:
    return " ".join((getattr(obj, "__doc__", "") or "").split())


def render() -> str:
    out = [
        "# GIE contract field reference",
        "",
        "> GENERATED by `python -m tools.render_contract_docs` from `gie/contracts/`. Do not edit.",
        f"> Contract set version {gie.contracts.CONTRACT_SET_VERSION}. The prose rules are in",
        "> `specifications/SHARED_CONTRACTS.md`; the machine-readable form is in",
        "> `gie/contracts/schemas/`.",
        "",
    ]
    nested: dict[str, type[Record]] = {}
    enums: dict[str, type[Enum]] = {}
    for name, record_type in all_contracts().items():
        out += [f"## {name} {record_type.VERSION}", "", _doc(record_type), ""]
        out += [*_table(record_type), ""]
        for spec in record_type.FIELD_SPECS:
            _walk(spec.ftype, nested, enums)
    out += ["## Nested value objects", ""]
    for name in sorted(nested):
        out += [f"### {name}", "", _doc(nested[name]), "", *_table(nested[name]), ""]
    out += ["## Enumerations", ""]
    for name in sorted(enums):
        values = ", ".join(f"`{member.value}`" for member in enums[name])
        out += [f"### {name}", "", _doc(enums[name]), "", f"Values: {values}", ""]
    out += [
        "## Order state machine",
        "",
        "`(state before, event) -> states allowed after`; no event may follow a terminal state.",
        "",
        "| state before | event | states after |",
        "|---|---|---|",
    ]
    for (before, event), after in sorted(
        ORDER_TRANSITIONS.items(),
        key=lambda item: ("" if item[0][0] is None else item[0][0].value, item[0][1].value),
    ):
        states = ", ".join(sorted(state.value for state in after))
        out.append(f"| {'(none)' if before is None else before.value} | {event.value} | {states} |")
    out += ["", "## Model status transitions", "", "| status before | statuses after |", "|---|---|"]
    for status, allowed in MODEL_STATUS_TRANSITIONS.items():
        after_text = ", ".join(sorted(item.value for item in allowed)) or "(terminal)"
        out.append(f"| {'(unregistered)' if status is None else status.value} | {after_text} |")
    out += ["", "## Identifier prefixes", "", "| prefix | meaning |", "|---|---|"]
    out += [f"| `{prefix}` | {meaning} |" for prefix, meaning in ID_PREFIXES.items()]
    out += [
        "",
        "## Stream ranks (tie-break at equal availability time)",
        "",
        "| rank | stream class |",
        "|---|---|",
    ]
    out += [f"| {rank.value} | {rank.name} |" for rank in StreamRank]
    out += ["", "## Error codes", "", "| code | class | meaning |", "|---|---|---|"]
    out += [f"| `{t.code}` | `{t.__name__}` | {_esc(_doc(t))} |" for t in ALL_ERROR_TYPES]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the contract field reference.")
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"PROBLEM: {OUTPUT} is stale; run python -m tools.render_contract_docs", file=sys.stderr)
            return 1
        print("contract field reference is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
